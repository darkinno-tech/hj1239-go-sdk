package gen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// Generator reads Go source files with hj1239 struct tags and generates
// MarshalBinary/UnmarshalBinary methods.

type Generator struct {
	buf strings.Builder
	pkg string
}

type FieldInfo struct {
	Name       string
	Type       string
	Offset     string
	Len        string
	Scale      string
	OffsetVal  string
	Unit       string
	Desc       string
	IsVar      bool
	IsScaled   bool
	ScaledType string
}

type StructInfo struct {
	Name   string
	Fields []FieldInfo
}

const marshalTemplate = `// Code generated by hj1239 gen; DO NOT EDIT.

package {{.Package}}

import "encoding/binary"

`

// Run starts the code generator for all .go files in the given directories
func Run(pkgPath string) error {
	entries, err := os.ReadDir(pkgPath)
	if err != nil {
		return fmt.Errorf("read dir %s: %w", pkgPath, err)
	}

	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		if strings.HasSuffix(entry.Name(), "_gen.go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}

		filePath := filepath.Join(pkgPath, entry.Name())
		f, err := parser.ParseFile(fset, filePath, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parse %s: %w", filePath, err)
		}

		pkgName := f.Name.Name

		var structs []StructInfo
		for _, decl := range f.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				structType, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					continue
				}

				si := StructInfo{Name: typeSpec.Name.Name}
				for _, field := range structType.Fields.List {
					if len(field.Names) == 0 {
						continue
					}
					fi := FieldInfo{
						Name: field.Names[0].Name,
						Type: typeExprToString(field.Type),
					}

					if field.Tag != nil {
						tag := field.Tag.Value
						tag = strings.Trim(tag, "`")
						fi.parseTag(tag)
					}
					if fi.Len == "" && !fi.IsVar {
						continue
					}
					si.Fields = append(si.Fields, fi)
				}
				if len(si.Fields) > 0 {
					structs = append(structs, si)
				}
			}
		}

		if len(structs) == 0 {
			continue
		}

		// Generate code
		var genBuf strings.Builder
		genBuf.WriteString(fmt.Sprintf("// Code generated by hj1239 gen; DO NOT EDIT.\n\npackage %s\n\n", pkgName))
		genBuf.WriteString(`import (
	"encoding/binary"
	"fmt"
)

`)

		for _, s := range structs {
			genBuf.WriteString(generateMarshalUnmarshal(s))
		}

		genFileName := strings.TrimSuffix(entry.Name(), ".go") + "_gen.go"
		genFilePath := filepath.Join(pkgPath, genFileName)
		if err := os.WriteFile(genFilePath, []byte(genBuf.String()), 0644); err != nil {
			return fmt.Errorf("write %s: %w", genFilePath, err)
		}
		fmt.Printf("Generated %s\n", genFilePath)
	}

	return nil
}

func (fi *FieldInfo) parseTag(tag string) {
	// Remove the key prefix if present (hj1239:"...")
	for {
		idx := strings.Index(tag, ":")
		if idx < 0 {
			break
		}
		key := tag[:idx]
		if key == `hj1239` || key == `json` {
			rest := tag[idx+1:]
			if len(rest) > 1 && rest[0] == '"' {
				// Find closing quote
				end := strings.Index(rest[1:], `"`)
				if end >= 0 {
					tag = rest[1 : end+1]
				}
			}
			break
		}
		tag = tag[idx+1:]
	}

	parts := strings.Split(tag, ",")
	for _, part := range parts {
		kv := strings.SplitN(part, ":", 2)
		if len(kv) != 2 {
			continue
		}
		switch kv[0] {
		case "offset":
			fi.Offset = kv[1]
		case "len":
			fi.Len = strings.TrimSpace(kv[1])
			if fi.Len == "var" {
				fi.IsVar = true
			}
		case "scale":
			fi.Scale = kv[1]
		case "offset_val":
			fi.OffsetVal = kv[1]
		case "unit":
			fi.Unit = kv[1]
		case "desc":
			fi.Desc = kv[1]
		}
	}
}

func typeExprToString(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return typeExprToString(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		if t.Len == nil {
			return "[]" + typeExprToString(t.Elt)
		}
		return "[" + typeExprToString(t.Len) + "]" + typeExprToString(t.Elt)
	case *ast.StarExpr:
		return "*" + typeExprToString(t.X)
	default:
		return fmt.Sprintf("%T", expr)
	}
}

func generateMarshalUnmarshal(s StructInfo) string {
	var buf strings.Builder

	// MarshalBinary
	buf.WriteString(fmt.Sprintf("// MarshalBinary encodes %s to binary format (GB1239)\n", s.Name))
	buf.WriteString(fmt.Sprintf("func (m *%s) MarshalBinary() ([]byte, error) {\n", s.Name))
	buf.WriteString("\ttotalSize := m.Size()\n")
	buf.WriteString("\tbuf := make([]byte, totalSize)\n")
	buf.WriteString("\tpos := 0\n\n")
	for _, f := range s.Fields {
		buf.WriteString(generateFieldEncode(f))
	}
	buf.WriteString("\treturn buf, nil\n")
	buf.WriteString("}\n\n")

	// UnmarshalBinary
	buf.WriteString(fmt.Sprintf("// UnmarshalBinary decodes %s from binary format (GB1239)\n", s.Name))
	buf.WriteString(fmt.Sprintf("func (m *%s) UnmarshalBinary(data []byte) error {\n", s.Name))
	buf.WriteString("\tpos := 0\n\n")
	for _, f := range s.Fields {
		buf.WriteString(generateFieldDecode(f))
	}
	buf.WriteString("\treturn nil\n")
	buf.WriteString("}\n")

	return buf.String()
}

func generateFieldEncode(f FieldInfo) string {
	switch {
	case f.Type == "uint8", f.Type == "byte":
		return fmt.Sprintf("\tbuf[pos] = m.%s\n\tpos++\n\n", f.Name)
	case f.Type == "uint16":
		return fmt.Sprintf("\tbinary.BigEndian.PutUint16(buf[pos:pos+2], m.%s)\n\tpos += 2\n\n", f.Name)
	case f.Type == "uint32":
		return fmt.Sprintf("\tbinary.BigEndian.PutUint32(buf[pos:pos+4], m.%s)\n\tpos += 4\n\n", f.Name)
	case f.Type == "int16":
		return fmt.Sprintf("\tbinary.BigEndian.PutUint16(buf[pos:pos+2], uint16(m.%s))\n\tpos += 2\n\n", f.Name)
	case f.Type == "int32":
		return fmt.Sprintf("\tbinary.BigEndian.PutUint32(buf[pos:pos+4], uint32(m.%s))\n\tpos += 4\n\n", f.Name)
	case f.Type == "GB1239Time", f.Type == "model.GB1239Time":
		return fmt.Sprintf("\tcopy(buf[pos:pos+6], m.%s.Bytes())\n\tpos += 6\n\n", f.Name)
	case isScaledType(f.Type):
		scaledType := scaledBaseName(f.Type)
		switch scaledType {
		case "ScaledUint8":
			return fmt.Sprintf("\tm.%s.PutUint8(buf[pos:pos+1])\n\tpos++\n\n", f.Name)
		case "ScaledInt8":
			return fmt.Sprintf("\tm.%s.PutInt8(buf[pos:pos+1])\n\tpos++\n\n", f.Name)
		case "ScaledUint16":
			return fmt.Sprintf("\tm.%s.PutUint16(buf[pos:pos+2], true)\n\tpos += 2\n\n", f.Name)
		case "ScaledInt16":
			return fmt.Sprintf("\tm.%s.PutInt16(buf[pos:pos+2], true)\n\tpos += 2\n\n", f.Name)
		case "ScaledUint32":
			return fmt.Sprintf("\tm.%s.PutUint32(buf[pos:pos+4], true)\n\tpos += 4\n\n", f.Name)
		}
	case f.Type == "string":
		l := f.Len
		if f.IsVar {
			return fmt.Sprintf("\tcopy(buf[pos:], []byte(m.%s))\n\tpos += len(m.%s)\n\n", f.Name, f.Name)
		}
		return fmt.Sprintf("\tcopy(buf[pos:pos+%s], []byte(m.%s))\n\tpos += %s\n\n", l, f.Name, l)
	case f.Type == "[]byte":
		if f.IsVar {
			return fmt.Sprintf("\tcopy(buf[pos:], m.%s)\n\tpos += len(m.%s)\n\n", f.Name, f.Name)
		}
		l := f.Len
		return fmt.Sprintf("\tcopy(buf[pos:pos+%s], m.%s)\n\tpos += %s\n\n", l, f.Name, l)
	}
	return fmt.Sprintf("\t// TODO: encode %s (type %s)\n\n", f.Name, f.Type)
}

func generateFieldDecode(f FieldInfo) string {
	switch {
	case f.Type == "uint8", f.Type == "byte":
		return fmt.Sprintf("\tif pos+1 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = data[pos]\n\tpos++\n\n", f.Name, f.Name)
	case f.Type == "uint16":
		return fmt.Sprintf("\tif pos+2 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = binary.BigEndian.Uint16(data[pos:pos+2])\n\tpos += 2\n\n", f.Name, f.Name)
	case f.Type == "uint32":
		return fmt.Sprintf("\tif pos+4 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = binary.BigEndian.Uint32(data[pos:pos+4])\n\tpos += 4\n\n", f.Name, f.Name)
	case f.Type == "int16":
		return fmt.Sprintf("\tif pos+2 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = int16(binary.BigEndian.Uint16(data[pos:pos+2]))\n\tpos += 2\n\n", f.Name, f.Name)
	case f.Type == "int32":
		return fmt.Sprintf("\tif pos+4 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = int32(binary.BigEndian.Uint32(data[pos:pos+4]))\n\tpos += 4\n\n", f.Name, f.Name)
	case f.Type == "GB1239Time", f.Type == "model.GB1239Time":
		return fmt.Sprintf("\tif pos+6 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s, _ = ParseGB1239Time(data[pos:pos+6])\n\tpos += 6\n\n", f.Name, f.Name)
	case isScaledType(f.Type):
		scaledType := scaledBaseName(f.Type)
		switch scaledType {
		case "ScaledUint8":
			return fmt.Sprintf("\tif pos+1 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s.DecodeUint8(data[pos:pos+1])\n\tpos++\n\n", f.Name, f.Name)
		case "ScaledInt8":
			return fmt.Sprintf("\tif pos+1 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s.DecodeInt8(data[pos:pos+1])\n\tpos++\n\n", f.Name, f.Name)
		case "ScaledUint16":
			return fmt.Sprintf("\tif pos+2 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s.DecodeUint16(data[pos:pos+2], true)\n\tpos += 2\n\n", f.Name, f.Name)
		case "ScaledInt16":
			return fmt.Sprintf("\tif pos+2 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s.DecodeInt16(data[pos:pos+2], true)\n\tpos += 2\n\n", f.Name, f.Name)
		case "ScaledUint32":
			return fmt.Sprintf("\tif pos+4 > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s.DecodeUint32(data[pos:pos+4], true)\n\tpos += 4\n\n", f.Name, f.Name)
		}
	case f.Type == "string":
		l := f.Len
		if f.IsVar {
			return fmt.Sprintf("\tm.%s = string(data[pos:])\n\tpos = len(data)\n\n", f.Name)
		}
		return fmt.Sprintf("\tif pos+%s > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = string(data[pos:pos+%s])\n\tpos += %s\n\n", l, f.Name, f.Name, l, l)
	case f.Type == "[]byte":
		if f.IsVar {
			return fmt.Sprintf("\tm.%s = make([]byte, len(data)-pos)\n\tcopy(m.%s, data[pos:])\n\tpos = len(data)\n\n", f.Name, f.Name)
		}
		l := f.Len
		return fmt.Sprintf("\tif pos+%s > len(data) { return fmt.Errorf(\"%%s: short read\", \"%s\") }\n\tm.%s = make([]byte, %s)\n\tcopy(m.%s, data[pos:pos+%s])\n\tpos += %s\n\n", l, f.Name, f.Name, l, f.Name, l, l)
	case f.Type == "*SignatureInfo", f.Type == "*model.SignatureInfo":
		return fmt.Sprintf("\tm.%s = &SignatureInfo{}\n\tif err := m.%s.Decode(data[pos:]); err != nil { return err }\n\tpos += m.%s.Size()\n\n", f.Name, f.Name, f.Name)
	}
	return fmt.Sprintf("\t// TODO: decode %s (type %s)\n\n", f.Name, f.Type)
}

func isScaledType(t string) bool {
	return strings.HasPrefix(t, "Scaled") || strings.HasPrefix(t, "model.Scaled")
}

func scaledBaseName(t string) string {
	return strings.TrimPrefix(t, "model.")
}


